-- =====================================================================
-- ny-hirako : schéma de la base de données (PostgreSQL 13 ou plus)
-- Usage : psql -d nyhirako -f db/schema.sql
-- Ce script supprime puis recrée toutes les tables : il remet la base à zéro.
