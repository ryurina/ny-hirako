BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;  -- hachage bcrypt des mots de passe (crypt / gen_salt)

-- ---------------------------------------------------------------------
-- Remise à zéro
-- ---------------------------------------------------------------------
DROP VIEW     IF EXISTS vue_droits_par_personne;
DROP TABLE    IF EXISTS repartition   CASCADE;
DROP TABLE    IF EXISTS diffusion     CASCADE;
DROP TABLE    IF EXISTS diffuseur     CASCADE;
DROP TABLE    IF EXISTS contribution  CASCADE;
DROP TABLE    IF EXISTS oeuvre        CASCADE;
DROP TABLE    IF EXISTS personne      CASCADE;
DROP TABLE    IF EXISTS role          CASCADE;
DROP TABLE    IF EXISTS utilisateur   CASCADE;

DROP FUNCTION IF EXISTS calculer_repartition(INT);
DROP FUNCTION IF EXISTS fn_trg_somme_parts();
DROP FUNCTION IF EXISTS fn_controle_somme_oeuvre(INT);
DROP FUNCTION IF EXISTS fn_verifier_editeur();
DROP FUNCTION IF EXISTS fn_valider_oeuvre();
DROP FUNCTION IF EXISTS fn_verifier_repartition();
DROP FUNCTION IF EXISTS fn_verifier_contributeur_valide();
DROP FUNCTION IF EXISTS fn_verifier_type_personne();
DROP FUNCTION IF EXISTS fn_verifier_statut_personne();

DROP TYPE IF EXISTS enum_type_personne;
DROP TYPE IF EXISTS enum_statut_validation;
DROP TYPE IF EXISTS enum_type_diffuseur;
DROP TYPE IF EXISTS enum_role_utilisateur;

-- ---------------------------------------------------------------------
-- Types énumérés
-- ---------------------------------------------------------------------
CREATE TYPE enum_type_personne     AS ENUM ('PHYSIQUE', 'MORALE');
CREATE TYPE enum_statut_validation AS ENUM ('EN_ATTENTE', 'VALIDE', 'REJETE');
CREATE TYPE enum_type_diffuseur    AS ENUM ('RADIO', 'TV', 'SALLE', 'EVENEMENT');
CREATE TYPE enum_role_utilisateur  AS ENUM ('ADMIN', 'MODERATEUR');

-- ---------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------

-- Comptes des modérateurs et administrateurs (les visiteurs n'ont pas de compte)
CREATE TABLE utilisateur (
    id_utilisateur    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             VARCHAR(255) NOT NULL UNIQUE,
    mot_de_passe_hash TEXT         NOT NULL,
    role_utilisateur  enum_role_utilisateur NOT NULL DEFAULT 'MODERATEUR',
    CONSTRAINT ck_utilisateur_email CHECK (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')
);

-- Ayants droit : personnes physiques (auteurs, compositeurs...) ou morales (éditeurs)
CREATE TABLE personne (
    id_personne    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type           enum_type_personne     NOT NULL,
    nom            VARCHAR(150)           NOT NULL,   -- raison sociale pour une personne morale
    prenom         VARCHAR(100),
    nom_artiste    VARCHAR(150),
    date_naissance DATE,
    telephone      VARCHAR(30),
    email          VARCHAR(255),
    ville          VARCHAR(100),
    statut         enum_statut_validation NOT NULL DEFAULT 'EN_ATTENTE',
    id_valideur    INT REFERENCES utilisateur (id_utilisateur) ON DELETE SET NULL,
    CONSTRAINT ck_personne_physique_prenom CHECK (type = 'MORALE' OR prenom IS NOT NULL),
    CONSTRAINT ck_personne_morale_champs   CHECK (type = 'PHYSIQUE' OR (prenom IS NULL AND date_naissance IS NULL)),
    CONSTRAINT ck_personne_naissance       CHECK (date_naissance IS NULL OR date_naissance <= CURRENT_DATE),
    CONSTRAINT ck_personne_email           CHECK (email IS NULL OR email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')
);

-- Rôles possibles sur une œuvre
CREATE TABLE role (
    id_role INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(50) NOT NULL UNIQUE
);

-- Œuvres musicales
CREATE TABLE oeuvre (
    id_oeuvre        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre            VARCHAR(255) NOT NULL,
    code_iswc        VARCHAR(15)  UNIQUE,
    annee_creation   INT,
    genre            VARCHAR(80),
    duree_sec        INT,
    statut           enum_statut_validation NOT NULL DEFAULT 'EN_ATTENTE',
    soumetteur_email VARCHAR(255),
    date_soumission  DATE NOT NULL DEFAULT CURRENT_DATE,
    id_valideur      INT REFERENCES utilisateur (id_utilisateur) ON DELETE SET NULL,
    CONSTRAINT ck_oeuvre_iswc  CHECK (code_iswc IS NULL OR code_iswc ~ '^T-[0-9]{3}\.[0-9]{3}\.[0-9]{3}-[0-9]$'),
    CONSTRAINT ck_oeuvre_annee CHECK (annee_creation IS NULL OR annee_creation BETWEEN 1800 AND 2100),
    CONSTRAINT ck_oeuvre_duree CHECK (duree_sec IS NULL OR duree_sec > 0),
    CONSTRAINT ck_oeuvre_soumetteur_email CHECK (soumetteur_email IS NULL OR soumetteur_email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')
);

-- Association ternaire personne / rôle / œuvre, avec la part de droits
CREATE TABLE contribution (
    id_contribution INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_oeuvre       INT          NOT NULL REFERENCES oeuvre   (id_oeuvre)   ON DELETE CASCADE,
    id_personne     INT          NOT NULL REFERENCES personne (id_personne) ON DELETE RESTRICT,
    id_role         INT          NOT NULL REFERENCES role     (id_role)     ON DELETE RESTRICT,
    part_pct        NUMERIC(5,2) NOT NULL,
    CONSTRAINT ck_contribution_part  CHECK (part_pct > 0 AND part_pct <= 100),
    CONSTRAINT uq_contribution_triplet UNIQUE (id_oeuvre, id_personne, id_role)
);

-- Radios, télévisions, salles, événements...
CREATE TABLE diffuseur (
    id_diffuseur INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom          VARCHAR(150)        NOT NULL,
    type         enum_type_diffuseur NOT NULL,
    ville        VARCHAR(100)        NOT NULL,
    CONSTRAINT uq_diffuseur_nom_ville UNIQUE (nom, ville)
);

-- Passage d'une œuvre chez un diffuseur (montant en Ariary)
CREATE TABLE diffusion (
    id_diffusion   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_oeuvre      INT           NOT NULL REFERENCES oeuvre    (id_oeuvre)    ON DELETE RESTRICT,
    id_diffuseur   INT           NOT NULL REFERENCES diffuseur (id_diffuseur) ON DELETE RESTRICT,
    date_diffusion DATE          NOT NULL,
    montant_total  NUMERIC(12,2) NOT NULL,
    CONSTRAINT ck_diffusion_montant CHECK (montant_total >= 0)
);

-- Droits versés à chaque contribution pour une diffusion (historique conservé)
CREATE TABLE repartition (
    id_diffusion    INT           NOT NULL REFERENCES diffusion    (id_diffusion)    ON DELETE CASCADE,
    id_contribution INT           NOT NULL REFERENCES contribution (id_contribution) ON DELETE RESTRICT,
    montant         NUMERIC(12,2) NOT NULL,
    PRIMARY KEY (id_diffusion, id_contribution),
    CONSTRAINT ck_repartition_montant CHECK (montant >= 0)
);

-- ---------------------------------------------------------------------
-- Index (clés étrangères et recherche)
-- ---------------------------------------------------------------------
CREATE INDEX idx_personne_statut      ON personne     (statut);
CREATE INDEX idx_personne_nom         ON personne     (lower(nom));
CREATE INDEX idx_oeuvre_statut        ON oeuvre       (statut);
CREATE INDEX idx_oeuvre_titre         ON oeuvre       (lower(titre));
CREATE INDEX idx_contribution_personne ON contribution (id_personne);
CREATE INDEX idx_diffusion_oeuvre     ON diffusion    (id_oeuvre);
CREATE INDEX idx_diffusion_diffuseur  ON diffusion    (id_diffuseur);
CREATE INDEX idx_repartition_contribution ON repartition (id_contribution);

-- ---------------------------------------------------------------------
-- Règle : seule une personne morale peut avoir le rôle « Éditeur »
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_verifier_editeur() RETURNS TRIGGER AS $$
DECLARE
    v_libelle role.libelle%TYPE;
    v_type    enum_type_personne;
BEGIN
    SELECT libelle INTO v_libelle FROM role WHERE id_role = NEW.id_role;

    IF v_libelle = 'Éditeur' THEN
        SELECT type INTO v_type FROM personne WHERE id_personne = NEW.id_personne;
        IF v_type <> 'MORALE' THEN
            RAISE EXCEPTION 'Seule une personne morale peut avoir le rôle Éditeur (personne %)', NEW.id_personne
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_verifier_editeur
BEFORE INSERT OR UPDATE ON contribution
FOR EACH ROW EXECUTE FUNCTION fn_verifier_editeur();

-- ---------------------------------------------------------------------
-- Règle : la somme des parts d'une œuvre validée vaut 100
-- Contrôle différé : il est vérifié au COMMIT, ce qui permet d'insérer
-- ou de modifier plusieurs contributions dans la même transaction.
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_controle_somme_oeuvre(p_id_oeuvre INT) RETURNS VOID AS $$
DECLARE
    v_statut enum_statut_validation;
    v_somme  NUMERIC;
BEGIN
    SELECT statut INTO v_statut FROM oeuvre WHERE id_oeuvre = p_id_oeuvre;

    IF v_statut = 'VALIDE' THEN
        SELECT COALESCE(SUM(part_pct), 0) INTO v_somme
        FROM contribution WHERE id_oeuvre = p_id_oeuvre;

        IF v_somme <> 100 THEN
            RAISE EXCEPTION 'La somme des parts de l''œuvre % vaut % au lieu de 100', p_id_oeuvre, v_somme
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION fn_trg_somme_parts() RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        PERFORM fn_controle_somme_oeuvre(NEW.id_oeuvre);
    END IF;
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        PERFORM fn_controle_somme_oeuvre(OLD.id_oeuvre);
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_somme_parts
AFTER INSERT OR UPDATE OR DELETE ON contribution
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION fn_trg_somme_parts();

-- ---------------------------------------------------------------------
-- Règle : pour valider une œuvre, la somme des parts vaut 100 et tous
-- les ayants droit concernés sont déjà validés
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_valider_oeuvre() RETURNS TRIGGER AS $$
DECLARE
    v_somme      NUMERIC;
    v_non_valide INT;
BEGIN
    IF NEW.statut = 'VALIDE' AND OLD.statut <> 'VALIDE' THEN
        SELECT COALESCE(SUM(part_pct), 0) INTO v_somme
        FROM contribution WHERE id_oeuvre = NEW.id_oeuvre;

        IF v_somme <> 100 THEN
            RAISE EXCEPTION 'Validation impossible : la somme des parts de l''œuvre % vaut % au lieu de 100', NEW.id_oeuvre, v_somme
                USING ERRCODE = 'check_violation';
        END IF;

        SELECT COUNT(*) INTO v_non_valide
        FROM contribution c
        JOIN personne p ON p.id_personne = c.id_personne
        WHERE c.id_oeuvre = NEW.id_oeuvre AND p.statut <> 'VALIDE';

        IF v_non_valide > 0 THEN
            RAISE EXCEPTION 'Validation impossible : % ayant(s) droit de l''œuvre % ne sont pas encore validés', v_non_valide, NEW.id_oeuvre
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_valider_oeuvre
BEFORE UPDATE OF statut ON oeuvre
FOR EACH ROW EXECUTE FUNCTION fn_valider_oeuvre();

-- ---------------------------------------------------------------------
-- Règle : une ligne de répartition concerne une contribution de la
-- même œuvre que la diffusion
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_verifier_repartition() RETURNS TRIGGER AS $$
DECLARE
    v_oeuvre_diffusion    INT;
    v_oeuvre_contribution INT;
BEGIN
    SELECT id_oeuvre INTO v_oeuvre_diffusion    FROM diffusion    WHERE id_diffusion    = NEW.id_diffusion;
    SELECT id_oeuvre INTO v_oeuvre_contribution FROM contribution WHERE id_contribution = NEW.id_contribution;

    IF v_oeuvre_diffusion IS DISTINCT FROM v_oeuvre_contribution THEN
        RAISE EXCEPTION 'La contribution % ne concerne pas l''œuvre de la diffusion %', NEW.id_contribution, NEW.id_diffusion
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_verifier_repartition
BEFORE INSERT OR UPDATE ON repartition
FOR EACH ROW EXECUTE FUNCTION fn_verifier_repartition();

-- ---------------------------------------------------------------------
-- Règles sur les ayants droit (voir aussi db/migrations/001_regles_personnes.sql)
-- ---------------------------------------------------------------------
-- Règle : une œuvre validée ne peut contenir que des ayants droit validés
CREATE OR REPLACE FUNCTION fn_verifier_contributeur_valide() RETURNS TRIGGER AS $$
DECLARE
    v_statut_oeuvre   enum_statut_validation;
    v_statut_personne enum_statut_validation;
BEGIN
    SELECT statut INTO v_statut_oeuvre FROM oeuvre WHERE id_oeuvre = NEW.id_oeuvre;

    IF v_statut_oeuvre = 'VALIDE' THEN
        SELECT statut INTO v_statut_personne FROM personne WHERE id_personne = NEW.id_personne;
        IF v_statut_personne <> 'VALIDE' THEN
            RAISE EXCEPTION 'La personne % n''est pas validée : elle ne peut pas être ajoutée à l''œuvre validée %', NEW.id_personne, NEW.id_oeuvre
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_verifier_contributeur_valide ON contribution;
CREATE TRIGGER trg_verifier_contributeur_valide
BEFORE INSERT OR UPDATE ON contribution
FOR EACH ROW EXECUTE FUNCTION fn_verifier_contributeur_valide();

-- Règle : une personne qui est éditeur d'une œuvre doit rester une personne morale
CREATE OR REPLACE FUNCTION fn_verifier_type_personne() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.type = 'PHYSIQUE' AND OLD.type <> 'PHYSIQUE' AND EXISTS (
        SELECT 1
        FROM contribution c
        JOIN role r ON r.id_role = c.id_role
        WHERE c.id_personne = NEW.id_personne AND r.libelle = 'Éditeur'
    ) THEN
        RAISE EXCEPTION 'La personne % est éditeur d''une œuvre : elle doit rester une personne morale', NEW.id_personne
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_verifier_type_personne ON personne;
CREATE TRIGGER trg_verifier_type_personne
BEFORE UPDATE OF type ON personne
FOR EACH ROW EXECUTE FUNCTION fn_verifier_type_personne();

-- Règle : on ne peut pas retirer la validation d'une personne liée à une œuvre validée
CREATE OR REPLACE FUNCTION fn_verifier_statut_personne() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.statut <> 'VALIDE' AND OLD.statut = 'VALIDE' AND EXISTS (
        SELECT 1
        FROM contribution c
        JOIN oeuvre o ON o.id_oeuvre = c.id_oeuvre
        WHERE c.id_personne = NEW.id_personne AND o.statut = 'VALIDE'
    ) THEN
        RAISE EXCEPTION 'La personne % est liée à des œuvres validées : son statut ne peut pas être modifié', NEW.id_personne
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_verifier_statut_personne ON personne;
CREATE TRIGGER trg_verifier_statut_personne
BEFORE UPDATE OF statut ON personne
FOR EACH ROW EXECUTE FUNCTION fn_verifier_statut_personne();

-- ---------------------------------------------------------------------
-- Calcul de la répartition des droits d'une diffusion
-- montant = montant_total x part_pct / 100, arrondi au centime.
-- Retourne le nombre de lignes créées ou mises à jour.
-- ---------------------------------------------------------------------
CREATE FUNCTION calculer_repartition(p_id_diffusion INT) RETURNS INT AS $$
DECLARE
    v_statut enum_statut_validation;
    v_nb     INT;
BEGIN
    SELECT o.statut INTO v_statut
    FROM diffusion d
    JOIN oeuvre o ON o.id_oeuvre = d.id_oeuvre
    WHERE d.id_diffusion = p_id_diffusion;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Diffusion % introuvable', p_id_diffusion
            USING ERRCODE = 'no_data_found';
    END IF;

    IF v_statut <> 'VALIDE' THEN
        RAISE EXCEPTION 'L''œuvre de la diffusion % n''est pas validée : répartition impossible', p_id_diffusion
            USING ERRCODE = 'check_violation';
    END IF;

    INSERT INTO repartition (id_diffusion, id_contribution, montant)
    SELECT d.id_diffusion, c.id_contribution, ROUND(d.montant_total * c.part_pct / 100, 2)
    FROM diffusion d
    JOIN contribution c ON c.id_oeuvre = d.id_oeuvre
    WHERE d.id_diffusion = p_id_diffusion
    ON CONFLICT (id_diffusion, id_contribution) DO UPDATE SET montant = EXCLUDED.montant;

    GET DIAGNOSTICS v_nb = ROW_COUNT;
    RETURN v_nb;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------
-- Vue : total des droits perçus par ayant droit
-- ---------------------------------------------------------------------
CREATE VIEW vue_droits_par_personne AS
SELECT p.id_personne,
       COALESCE(p.nom_artiste, TRIM(COALESCE(p.prenom, '') || ' ' || p.nom)) AS nom_affiche,
       COUNT(DISTINCT c.id_oeuvre)  AS nb_oeuvres,
       COALESCE(SUM(r.montant), 0)  AS total_droits
FROM personne p
LEFT JOIN contribution c ON c.id_personne = p.id_personne
LEFT JOIN repartition  r ON r.id_contribution = c.id_contribution
GROUP BY p.id_personne;

COMMIT;
